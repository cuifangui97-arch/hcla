async function saved(page:any){return JSON.parse((await page.locator("#ep09-state").textContent())||"{}");}
async function stepUntil(page:any,predicate:(state:any)=>boolean,max=220){for(let i=0;i<max;i++){const state=await saved(page);if(predicate(state))return;await page.getByRole("button",{name:"CAM"}).click();const button=page.locator(".e09-controls button.primary");await expect(button).toBeVisible();await button.click();}throw new Error("EP09 dialogue did not reach expected state; current save="+JSON.stringify(await saved(page)));}
async function phaseUntil(page:any,phase:string,max=220){await stepUntil(page,s=>s.v164Phase!==phase||phase==="TRAVEL_PLAY"&&s.travelIndex>=3||phase==="GIFT_PLAY"&&s.giftIndex>=5||phase==="FINAL_DATE_PLAY"&&s.dateIndex>=5-(s.datePairs?.length??0));}

